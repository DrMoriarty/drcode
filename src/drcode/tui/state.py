"""Textual-bound shared state of the :class:`~drcode.tui.app.DrCodeApp`
layer mixins.

The coding UI is split into several mixin layers (:mod:`chat_view`,
:mod:`actions`, :mod:`pipeline`) that are combined with the base ``App``
in a single :class:`~drcode.tui.app.DrCodeApp`. Every layer references a
large set of shared instance attributes that are only *assigned* inside
``DrCodeApp.__init__``; pyright cannot see those assignments from a
sibling mixin, so they are declared as class-level annotations here (and
in the UI-neutral :class:`drcode.core.state.CoreState` this class builds
on).

This module keeps ONLY the Textual-bound part: widget getters, widget-
and timer-typed bookkeeping and the action-layer protocol stubs whose
signatures carry Textual/widget types. Everything UI-neutral (the run
registries, settings, the pipeline bookkeeping, the per-role model
resolution) lives in :mod:`drcode.core.state`; the pipeline reaches the
UI through the ``host`` seam instead of this class.

There is intentionally no runtime value in the stubs —
``DrCodeApp.__init__`` still owns the actual assignment — so behaviour
is unchanged (reading an attribute before ``__init__`` still raises
``AttributeError`` exactly as before).
"""

